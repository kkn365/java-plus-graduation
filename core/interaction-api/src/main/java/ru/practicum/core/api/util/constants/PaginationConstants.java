package ru.practicum.core.api.util.constants;

/**
 * Константы для параметров пагинации.
 * <p>
 * Определяет значения по умолчанию и сообщения об ошибках для параметров 'from' и 'size',
 * используемых при запросе страниц с данными.
 */
public class PaginationConstants {

    /**
     * Значение по умолчанию для параметра 'from' (смещение).
     * <p>
     * Обозначает начальную позицию выборки данных. По умолчанию — 0.
     */
    public static final String DEFAULT_FROM = "0";

    /**
     * Сообщение об ошибке для параметра 'from'.
     * <p>
     * Используется, если значение 'from' меньше 0.
     */
    public static final String FROM_VALUE_ERROR = "Параметр 'from' не может быть меньше 0";

    /**
     * Значение по умолчанию для параметра 'size' (количество элементов на странице).
     * <p>
     * Указывает, сколько записей будет возвращено на одну страницу. По умолчанию — 10.
     */
    public static final String DEFAULT_SIZE = "10";

    /**
     * Сообщение об ошибке для параметра 'size'.
     * <p>
     * Используется, если значение 'size' меньше 1.
     */
    public static final String SIZE_VALUE_ERROR = "Параметр 'size' не может быть меньше 1";
}